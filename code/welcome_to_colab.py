def mle_alpha(data, xmin=1):
    """
    Maximum-Likelihood Estimator for discrete power-law exponent α.
    Based on Clauset, Shalizi & Newman (2009).
    """
    x = data[data >= xmin]
    if len(x) < 20:
        return np.nan
    return 1.0 + len(x) / np.sum(np.log(x / (xmin - 0.5)))


