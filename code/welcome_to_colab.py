class NeuronalAvalancheModel:
    """
    Simplified BTW-style cascade on a neural graph.

    Each neuron i carries 'charge' z[i].
    Drive: once per time-step, z[random neuron] += small noise.
    Fire: if z[i] >= threshold, neuron fires:
          z[i] → 0  (reset)
          each neighbour j: z[j] += coupling * z_fired / k_i
    Avalanche = chain of firings triggered by a single drive event.
    """

    def __init__(self, N=200, avg_k=8, network='random',
                 threshold=1.0, coupling=0.92, noise_amp=0.08):
        self.N          = N
        self.threshold  = threshold
        self.coupling   = coupling
        self.noise_amp  = noise_amp

        # ── Build graph ─────────────────────────────────
        if network == 'random':
            p  = avg_k / (N - 1)
            G  = nx.erdos_renyi_graph(N, p, seed=42)
        elif network == 'scale_free':
            m  = max(1, int(avg_k / 2))
            G  = nx.barabasi_albert_graph(N, m, seed=42)
        elif network == 'small_world':
            G  = nx.watts_strogatz_graph(N, max(2, int(avg_k)), 0.2, seed=42)
        else:
            raise ValueError(f"Unknown network: {network}")

        # Largest connected component
        lcc        = max(nx.connected_components(G), key=len)
        G          = G.subgraph(lcc).copy()
        G          = nx.convert_node_labels_to_integers(G)
        self.G     = G
        self.N     = G.number_of_nodes()
        self.adj   = [list(G.neighbors(i)) for i in range(self.N)]
        self.k     = np.array([G.degree(i) for i in range(self.N)], dtype=float)
        self.avg_k = float(self.k.mean())

        # Initialise membrane potentials
        self.z = np.random.uniform(0, 0.5 * threshold, self.N)

    # ── Single time-step ────────────────────────────────
    def step(self):
        # 1. NOISE  (slow external drive)
        t      = np.random.randint(self.N)
        self.z[t] += self.noise_amp * np.random.exponential(1.0)

        # 2. AVALANCHE propagation
        size     = 0
        duration = 0

        while True:
            firing = np.where(self.z >= self.threshold)[0]
            if len(firing) == 0:
                break
            size     += len(firing)
            duration += 1

            dz = np.zeros(self.N)
            for n in firing:
                nbs = self.adj[n]
                if nbs:
                    share = self.coupling * self.z[n] / len(nbs)
                    for nb in nbs:
                        dz[nb] += share
                self.z[n] = 0.0          # reset neuron
            self.z += dz

        return size, duration

    # ── Full run ────────────────────────────────────────
    def run(self, n_steps=60_000, warmup=8_000):
        for _ in range(warmup):
            self.step()

        sizes, durs = [], []
        for _ in range(n_steps):
            s, d = self.step()
            if s > 0:
                sizes.append(s)
                durs.append(d)
        return np.array(sizes), np.array(durs)


# ──────────────────────────────────────────────────────────
# POWER-LAW EXPONENT  (MLE, Clauset et al.)
